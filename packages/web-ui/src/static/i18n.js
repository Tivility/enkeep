/**
 * Record missing translation key for diagnostics (without console logging).
 */
function recordMissingKey(key, locale) {
  missingKeyTotalCount += 1;
  const statKey = locale + ":" + key;
  missingKeyStats[statKey] = (missingKeyStats[statKey] || 0) + 1;
}

/**
 * Returns total count of missing key accesses.
 */
export function getMissingKeyCount() {
  return missingKeyTotalCount;
}

/**
 * Returns copy of missing key diagnostics.
 */
export function getMissingKeyStats() {
  return { ...missingKeyStats };
}

/**
 * Reset missing key counter for test isolation.
 */
export function resetMissingKeyStats() {
  missingKeyTotalCount = 0;
  for (const k of Object.keys(missingKeyStats)) {
    delete missingKeyStats[k];
  }
}

/**
 * Returns the currently active locale.
 */
export function getLocale() {
  return currentLocale;
}

/**
 * Strict parameter interpolation replacing {name} placeholders.
 * Pure string operations without eval / Function.
 */
export function interpolate(template, params) {
  if (typeof template !== "string") {
    return "";
  }
  if (!params || typeof params !== "object") {
    return template;
  }
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, paramName) => {
    if (Object.prototype.hasOwnProperty.call(params, paramName)) {
      const val = params[paramName];
      return val !== null && val !== undefined ? String(val) : "";
    }
    return match;
  });
}

/**
 * Translate a key into the active locale with parameter interpolation.
 * Fallbacks to DEFAULT_LOCALE ("en") when missing.
 */
export function t(key, params) {
  if (typeof key !== "string" || key.length === 0) {
    return "";
  }

  const activeCatalog = catalogs[currentLocale] || catalogs[DEFAULT_LOCALE] || {};
  let template = activeCatalog[key];

  if (template === undefined) {
    recordMissingKey(key, currentLocale);

    // Fallback to default locale if not already active
    if (currentLocale !== DEFAULT_LOCALE) {
      const fallbackCatalog = catalogs[DEFAULT_LOCALE] || {};
      template = fallbackCatalog[key];
    }

    if (template === undefined) {
      if (strictMode) {
        throw new Error(
          "[i18n] Missing translation key \"" + key + "\" in locale \"" + currentLocale + "\" and fallback \"" + DEFAULT_LOCALE + "\""
        );
      }
      return interpolate(key, params);
    }
  }

  return interpolate(template, params);
}

/**
 * Resolve target locale based on strict decision hierarchy:
 * 1. Authenticated user canonical locale (user.locale)
 * 2. Storage preference (localStorage -> sessionStorage "enkeep.locale")
 * 3. Browser navigator language (zh* -> "zh-CN", else "en")
 * 4. Default "en"
 */
export function detectLocale(user = null) {
  // 1. User canonical flat locale
  if (user && typeof user === "object") {
    if (typeof user.locale === "string" && SUPPORTED_LOCALES.includes(user.locale)) {
      return user.locale;
    }
  }

  // 2. Storage preference
  try {
    if (typeof localStorage !== "undefined") {
      const saved = localStorage.getItem("enkeep.locale");
      if (saved && SUPPORTED_LOCALES.includes(saved)) {
        return saved;
      }
    }
  } catch {
    // Storage access blocked or unavailable
  }

  try {
    if (typeof sessionStorage !== "undefined") {
      const saved = sessionStorage.getItem("enkeep.locale");
      if (saved && SUPPORTED_LOCALES.includes(saved)) {
        return saved;
      }
    }
  } catch {
    // Storage access blocked or unavailable
  }

  // 3. Browser navigator language
  if (typeof navigator !== "undefined") {
    const navLang = navigator.language || (navigator.languages && navigator.languages[0]);
    if (typeof navLang === "string" && /^zh/i.test(navLang.trim())) {
      return "zh-CN";
    }
  }

  // 4. Default fallback
  return DEFAULT_LOCALE;
}

