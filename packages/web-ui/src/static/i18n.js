/**
 * Translate static DOM elements:
 * - [data-i18n]: el.textContent = t(key)
 * - [data-i18n-placeholder]: el.placeholder = t(key)
 * - [data-i18n-title]: el.title = t(key)
 * - [data-i18n-aria-label]: el.setAttribute("aria-label", t(key))
 */
export function translateDom(root) {
  const targetRoot = root || (typeof document !== "undefined" ? document : null);
  if (!targetRoot || typeof targetRoot.querySelectorAll !== "function") {
    return;
  }

  // 1. Text elements
  const textElements = targetRoot.querySelectorAll("[data-i18n]");
  for (let i = 0; i < textElements.length; i++) {
    const el = textElements[i];
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  }

  // 2. Placeholder attributes
  const placeholderElements = targetRoot.querySelectorAll("[data-i18n-placeholder]");
  for (let i = 0; i < placeholderElements.length; i++) {
    const el = placeholderElements[i];
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      const val = t(key);
      el.setAttribute("placeholder", val);
      if ("placeholder" in el) {
        el.placeholder = val;
      }
    }
  }

  // 3. Title attributes
  const titleElements = targetRoot.querySelectorAll("[data-i18n-title]");
  for (let i = 0; i < titleElements.length; i++) {
    const el = titleElements[i];
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      const val = t(key);
      el.setAttribute("title", val);
      if ("title" in el) {
        el.title = val;
      }
    }
  }

  // 4. Aria-label attributes
  const ariaElements = targetRoot.querySelectorAll("[data-i18n-aria-label]");
  for (let i = 0; i < ariaElements.length; i++) {
    const el = ariaElements[i];
    const key = el.getAttribute("data-i18n-aria-label");
    if (key) {
      el.setAttribute("aria-label", t(key));
    }
  }
}

/**
 * Set active locale, update document lang and DOM, persist, and dispatch event.
 */
export function setLocale(newLocale, options = {}) {
  let targetLocale = newLocale;
  if (!SUPPORTED_LOCALES.includes(targetLocale)) {
    targetLocale = DEFAULT_LOCALE;
  }

  const previousLocale = currentLocale;
  currentLocale = targetLocale;

  // Persist to localStorage unless persist: false
  if (options.persist !== false) {
    try {
      if (typeof localStorage !== "undefined") {
        localStorage.setItem("enkeep.locale", targetLocale);
      }
    } catch {
      // Storage unavailable
    }
  }

  // Update HTML tag lang
  if (typeof document !== "undefined" && document.documentElement) {
    document.documentElement.lang = targetLocale;
  }

  // Translate DOM nodes
  if (typeof document !== "undefined") {
    translateDom(document);
    syncLanguageControls(targetLocale);
  }

  // Dispatch custom event
  if (options.silent !== true) {
    const detail = { locale: targetLocale, previousLocale };
    if (typeof window !== "undefined" && typeof window.dispatchEvent === "function") {
      try {
        window.dispatchEvent(new CustomEvent("enkeep:localechange", { detail }));
      } catch {
        // Fallback
      }
    }
    if (typeof document !== "undefined" && typeof document.dispatchEvent === "function") {
      try {
        document.dispatchEvent(new CustomEvent("enkeep:localechange", { detail }));
      } catch {
        // Fallback
      }
    }
  }

  return currentLocale;
}

/**
 * Initialize i18n system during application bootstrap.
 */
export function initI18n(initialUser = null) {
  const resolved = detectLocale(initialUser);
  setLocale(resolved, { silent: false });
  return resolved;
}

